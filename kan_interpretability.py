def calculate_snr(signal, background):
    if len(background) == 0:
        return float('inf')  # Avoid division by zero
    return np.mean(signal) / np.std(background)

def batch_classification_with_snr(model, model_name, mlp_model, test_input, true_labels, batch_size=100):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    test_input = test_input.to(device).cpu().numpy()
    true_labels = true_labels.to(device).cpu().numpy()  # Ensure true labels are in NumPy format

    num_batches = len(test_input) // batch_size
    batch_snr_scores = []
    batch_indices = []
    selected_labels = []
    selected_preds_prob = []  # Store probabilities instead of binary predictions

    # Iterate over batches
    for i in range(num_batches):
        batch = test_input[i * batch_size:(i + 1) * batch_size]

        # Model-specific prediction logic
        if isinstance(model, xgb.XGBClassifier):
            preds = model.predict_proba(batch)[:, 1]  # XGBoost: Probability of the positive class
        elif isinstance(model, GaussianMixture):
            preds = model.predict_proba(batch)[:, 1]  # GMM: Probability of the "signal" class (component 1)
        elif isinstance(model, IsolationForest):
            preds = model.decision_function(batch)  # IF: Anomaly scores (higher means more likely signal)
            preds = (preds - np.min(preds)) / (np.max(preds) - np.min(preds))  # Normalize
        elif isinstance(model, AdaBoostClassifier):
            preds = model.predict_proba(batch)[:, 1]  # AdaBoost: Probability of the positive class

        # Separate signal and background based on the prediction
        signal = batch[preds >= 0.5]
        background = batch[preds < 0.5]
        snr = calculate_snr(signal, background)

        batch_snr_scores.append(snr)
        batch_indices.append(i)

    # Select batches whose SNR is greater than mean + standard deviation
    mean_snr = np.mean(batch_snr_scores)
    std_snr = np.std(batch_snr_scores)
    selected_batches = [i for i, snr in zip(batch_indices, batch_snr_scores) if snr > (mean_snr + std_snr)]
    full_data = []

    # Collect true labels and prediction probabilities from selected batches
    for i in selected_batches:
        batch = test_input[i * batch_size:(i + 1) * batch_size]
        full_data.append(batch)
        true_batch_labels = true_labels[i * batch_size:(i + 1) * batch_size]

        # Get MLP predictions
        mlp_inputs_tensor = torch.tensor(batch, dtype=torch.float32).to(device)
        mlp_logits = mlp_model(mlp_inputs_tensor).cpu().detach().numpy()  # Get raw logits

        # Apply Sigmoid to get probabilities
        mlp_probs = torch.sigmoid(torch.tensor(mlp_logits)).cpu().detach().numpy()

        selected_labels.append(true_batch_labels)
        selected_preds_prob.append(mlp_probs.flatten())  # Store probabilities for later use

    # Concatenate the selected labels and probabilities from the selected batches
    selected_labels = np.concatenate(selected_labels)
    selected_preds_prob = np.concatenate(selected_preds_prob)

    # Calculate metrics for the selected batches
    accuracy = accuracy_score(selected_labels, (selected_preds_prob >= 0.5).astype(int))  # Use threshold of 0.5 for accuracy
    precision = precision_score(selected_labels, (selected_preds_prob >= 0.5).astype(int), average='binary')
    recall = recall_score(selected_labels, (selected_preds_prob >= 0.5).astype(int), average='binary')
    f1 = f1_score(selected_labels, (selected_preds_prob >= 0.5).astype(int), average='binary')

    # Calculate significance as mean SNR across selected batches
    significance = np.mean([batch_snr_scores[i] for i in selected_batches])
    auc = roc_auc_score(selected_labels, selected_preds_prob)  # Use probabilities for AUC calculation

    # Print out the results
    print(f"Model: {model_name}")
    print(f"Accuracy: {accuracy:.4f}")
    print(f"Precision: {precision:.4f}")
    print(f"Recall: {recall:.4f}")
    print(f"F1 Score: {f1:.4f}")
    print(f"AUC: {auc:.4f}")
    print(f"Significance (Mean SNR): {significance:.4f}\n")

    # **Plot ROC Curve**
    fpr, tpr, _ = roc_curve(selected_labels, selected_preds_prob)
    plt.plot(fpr, tpr, label=f'{model_name} (AUC={auc:.4f})')


def calculate_metrics(y_true, y_pred, class_weights):
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
    accuracy = accuracy_score(y_true, y_pred)
    f1 = f1_score(y_true, y_pred)
    recall = recall_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred)

    return tp, fp, tn, fn, accuracy, f1, recall, precision

def train_step(model, optimizer, loss_fn, inputs, labels):
    optimizer.zero_grad()
    inputs = inputs.unsqueeze(0)
    outputs = model(inputs)
    outputs = outputs.view(-1)
    labels = labels.unsqueeze(0)
    loss = loss_fn(outputs, labels.float())
    loss.backward()
    optimizer.step()
    return loss.item()

def evaluate(model, inputs, labels, class_weights, threshold):
    model.eval()
    with torch.no_grad():
        outputs = model(inputs)
        #Apply Sigmoid before calculating metrics
        y_pred = (torch.sigmoid(outputs.squeeze()) > threshold).cpu().tolist()  # Apply sigmoid here
        y_true = labels.tolist()
    return calculate_metrics(y_true, y_pred, class_weights)

def train(model, train_input, train_label, validate_input, validate_label, optimizer, loss_fn, num_epochs, acc_list, class_weights, threshold):
    for epoch in range(num_epochs):
        epoch_loss = 0
        for i in range(len(train_input)):
            inputs = train_input[i]
            labels = train_label[i]
            loss = train_step(model, optimizer, loss_fn, inputs, labels)
            epoch_loss += loss
        print(f"Epoch {epoch+1}, Loss: {epoch_loss / len(train_input)}")
        tp, fp, tn, fn, accuracy, f1, recall, precision = evaluate(model, validate_input, validate_label, class_weights, threshold)
        acc_list.append(accuracy)
        print(f"Epoch {epoch+1}: TP={tp}, FP={fp}, TN={tn}, FN={fn}, Accuracy={accuracy:.4f}, F1={f1:.4f}, Recall={recall:.4f}, Precision={precision:.4f}")


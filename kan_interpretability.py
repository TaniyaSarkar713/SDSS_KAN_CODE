def cross_validate(model_class, X, y, num_epochs, learning_rate, weight_decay, class_weights, threshold):
    accuracies = []

    for fold, (train_idx, val_idx) in enumerate(kf.split(X)):
        print(f"Fold {fold+1}/{num_folds}")

        # Split data into training and validation sets
        train_input, val_input = X[train_idx], X[val_idx]
        train_label, val_label = y[train_idx], y[val_idx]

        # Move to device if using GPU
        train_input, val_input = train_input.to(device), val_input.to(device)
        train_label, val_label = train_label.to(device), val_label.to(device)

        # Forcefully reset the model

# --- AMS function ---
def AMS(s, b, b_reg=10.0):
    """ Approximate Median Significance """
    radicand = 2 * ((s + b + b_reg) * np.log(1.0 + s / (b + b_reg)) - s)
    return np.sqrt(radicand) if radicand > 0 else 0.0

# --- Two-Stage Evaluation Function ---
def two_stage_ams_evaluation(model, X, y, weights, batch_size=1000, threshold_method='mean+std', device='cpu'):
    # Ensure everything is in NumPy format
    if isinstance(X, pd.DataFrame): X = X.values
    if isinstance(y, pd.Series): y = y.values
    if isinstance(weights, pd.Series): weights = weights.values

    num_samples = X.shape[0]
    indices = np.random.permutation(num_samples)
    X_shuffled = X[indices]
    y_shuffled = y[indices]
    w_shuffled = weights[indices]

    num_batches = int(np.ceil(num_samples / batch_size))

    sb_ratios = []
    batch_data = []

    # Step 1: Train XGBoost once on full dataset
    xgb_model = xgb.XGBClassifier(use_label_encoder=False, eval_metric='logloss')
    xgb_model.fit(X, y)

    # Step 2: Evaluate each batch
    for i in range(num_batches):
        start = i * batch_size
        end = min((i + 1) * batch_size, num_samples)

        X_batch = X_shuffled[start:end]
        y_batch = y_shuffled[start:end]
        w_batch = w_shuffled[start:end]

        preds = xgb_model.predict(X_batch)

        signal_mask = (preds == 1)
        background_mask = (preds == 0)

        s = np.sum(w_batch[signal_mask & (y_batch == 1)])
        b = np.sum(w_batch[background_mask & (y_batch == 0)])

        sb_ratio = s / (b + 1e-6)  # Avoid division by zero
        sb_ratios.append(sb_ratio)
        batch_data.append((X_batch, y_batch, w_batch, s, b, sb_ratio))

    # Step 3: Determine threshold
    sb_ratios_array = np.array(sb_ratios)
    mean_sb = sb_ratios_array.mean()
    std_sb = sb_ratios_array.std()
    threshold = mean_sb + std_sb if threshold_method == 'mean+std' else np.median(sb_ratios_array)

    print(f"Threshold for S/B ratio: {threshold:.4f}")

    # Step 4: Filter batches
    selected_data = [bd for bd in batch_data if bd[5] > threshold]

    if not selected_data:
        print("No batches passed the S/B threshold.")
        return 0.0

    # Step 5: Concatenate selected data
    X_selected = np.vstack([bd[0] for bd in selected_data])
    y_selected = np.concatenate([bd[1] for bd in selected_data])
    w_selected = np.concatenate([bd[2] for bd in selected_data])

    # Step 6: Evaluate your model
    model.eval()
    with torch.no_grad():
        X_tensor = torch.tensor(X_selected, dtype=torch.float32).to(device)
        logits = model(X_tensor)
        probs = torch.sigmoid(logits).cpu().numpy().flatten()
        preds = (probs > 0.5).astype(int)

    # Step 7: Final AMS calculation
    s_final = np.sum(w_selected[(preds == 1) & (y_selected == 1)])
    b_final = np.sum(w_selected[(preds == 1) & (y_selected == 0)])
    ams_score = AMS(s_final, b_final)

    print(f"✅ Final AMS Score: {ams_score:.4f}")
    return ams_score


import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
from scipy.stats import pointbiserialr

#Point Biserial Correlation

# Create a dictionary to store correlations
correlations = {}

# For each feature
for col in df.columns:
    corr, _ = pointbiserialr(df[col], label)
    correlations[col] = corr  # Store the correlation

# Convert the dictionary to a pandas DataFrame
correlation_df = pd.DataFrame(list(correlations.items()), columns=["Feature", "Correlation"])

# Plotting the heatmap
plt.figure(figsize=(30, 4))  # Set the size for a 1-column heatmap
sns.heatmap(correlation_df.set_index("Feature").T, annot=True, cmap="coolwarm", cbar=True, center=0)

# Adjust the plot for better readability
plt.title("Feature vs. Correlation with Target")
plt.yticks(rotation=0)  # Keep the feature names on the y-axis
plt.xticks(rotation=90)  # Rotate the correlation labels on the x-axis if needed

plt.show()


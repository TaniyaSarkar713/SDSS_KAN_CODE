# Ensure device compatibility
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# Train XGBoost Classifier
def train_xgboost(X_train, y_train):
    xgb_model = xgb.XGBClassifier(
        objective="binary:logistic",
        eval_metric="logloss",
        use_label_encoder=False
    )
    xgb_model.fit(X_train, y_train)
    return xgb_model

# Function to apply hybrid classification (XGBoost + MLP)
def hybrid_classification(xgb_model, mlp_model, X_test, threshold=0.5):
    xgb_preds = xgb_model.predict_proba(X_test)[:, 1]  # Get XGBoost probabilities
    xgb_binary_preds = (xgb_preds > threshold).astype(int)  # Convert to binary labels

    # Convert X_test to tensor for MLP (Only for samples where XGBoost predicted 1)
    X_test_tensor = torch.tensor(X_test, dtype=torch.float32).to(device)
    mlp_model.eval()

    with torch.no_grad():
        mlp_logits = mlp_model(X_test_tensor).squeeze()  # Get raw MLP outputs
        mlp_probs = torch.sigmoid(mlp_logits).cpu().numpy()  # Convert logits to probabilities

    # Final hybrid predictions:
    # Use XGBoost predictions unless it predicts 1, then use MLP probability
    final_probs = np.where(xgb_binary_preds == 1, mlp_probs, xgb_preds)

    return final_probs

# Generate and plot the ROC-AUC curve
def plot_roc_auc(y_test, final_probs):
    fpr, tpr, _ = roc_curve(y_test, final_probs)
    roc_auc = auc(fpr, tpr)

    plt.figure(figsize=(8, 6))
    plt.plot(fpr, tpr, color="blue", lw=2, label=f"Hybrid Model (AUC = {roc_auc:.4f})")
    plt.plot([0, 1], [0, 1], color="gray", linestyle="--")  # Random classifier line
    plt.xlabel("False Positive Rate")
    plt.ylabel("True Positive Rate")
    plt.title("ROC-AUC Curve")
    plt.legend(loc="lower right")
    plt.show()

    print(f"ROC-AUC Score: {roc_auc:.4f}")

# Compute final accuracy
def compute_accuracy(y_test, final_probs, threshold=0.5):
    final_preds = (final_probs > threshold).astype(int)
    accuracy = accuracy_score(y_test, final_preds)
    print(f"Final Hybrid Model Accuracy: {accuracy:.4f}")
    return accuracy

